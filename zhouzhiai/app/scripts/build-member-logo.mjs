// Repackage the existing thin client with the existing company icon, not a redesigned logo.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const builderRequire=createRequire(require.resolve('electron-builder'));
const appBuilderRequire=createRequire(builderRequire.resolve('app-builder-lib'));
const ResEdit=appBuilderRequire('resedit');
const asar=appBuilderRequire('@electron/asar');
const output=path.resolve(process.argv[2]||path.join(root,'member-release-logo'));
if(fs.existsSync(output))throw Error('输出目录已存在，请指定新的目录以保留旧版安装包');
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'zhouzhi-logo-build-'));
fs.mkdirSync(output,{recursive:true});
const source=path.join(root,'public/brand/app-icon.png');
const iconFile=new ResEdit.Data.IconFile();
for(const size of [16,24,32,48,64,128,256]){
  const png=path.join(scratch,`logo-${size}.png`);
  execFileSync('/usr/bin/sips',['-z',String(size),String(size),source,'--out',png],{stdio:'ignore'});
  iconFile.icons.push({data:ResEdit.Data.RawIconItem.from(fs.readFileSync(png),size,size,32)});
}
const ico=Buffer.from(iconFile.generate());
fs.writeFileSync(path.join(root,'member-client/icon.ico'),ico);
fs.copyFileSync(source,path.join(root,'member-client/icon.png'));
fs.writeFileSync(path.join(output,'icon.ico'),ico);
fs.copyFileSync(source,path.join(output,'同舟图标.png'));
const unpacked=path.join(output,'win-unpacked');
const baseOption=process.argv.indexOf('--base-unpacked');
const base=baseOption>=0?path.resolve(process.argv[baseOption+1]):path.join(root,'member-release/win-unpacked');
assert.ok(fs.existsSync(path.join(base,'舟知.exe'))&&fs.existsSync(path.join(base,'resources/app.asar')),'缺少已验收的 Windows 运行时目录');
fs.cpSync(base,unpacked,{recursive:true});
fs.writeFileSync(path.join(unpacked,'zhouzhi-crossflow-v1.ico'),ico);
const appDir=path.join(scratch,'app');fs.mkdirSync(appDir);
for(const name of ['main.cjs','preload.cjs','credentials.cjs','navigation.cjs','package.json','icon.png'])fs.copyFileSync(path.join(root,'member-client',name),path.join(appDir,name));
await asar.createPackage(appDir,path.join(unpacked,'resources/app.asar'));
const packed=asar.listPackage(path.join(unpacked,'resources/app.asar')).sort();
assert.deepEqual(packed,['/credentials.cjs','/icon.png','/main.cjs','/navigation.cjs','/package.json','/preload.cjs']);
const exePath=path.join(unpacked,'舟知.exe');
const original=fs.readFileSync(exePath);
const exe=ResEdit.NtExecutable.from(original,{ignoreCert:true});
const machine=exe.newHeader.fileHeader.machine;
const res=ResEdit.NtExecutableResource.from(exe);
const groups=res.entries.filter(e=>e.type===14).map(e=>({id:e.id,lang:e.lang}));
assert.ok(groups.length,'客户端必须存在图标资源');
for(const group of groups)ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries,group.id,group.lang,iconFile.icons.map(i=>i.data));
res.outputResource(exe);
fs.writeFileSync(exePath,Buffer.from(exe.generate()));
const verifyExe=ResEdit.NtExecutable.from(fs.readFileSync(exePath));
assert.equal(verifyExe.newHeader.fileHeader.machine,machine);
const verifyRes=ResEdit.NtExecutableResource.from(verifyExe);
for(const size of [16,32,48,128,256])assert.ok(verifyRes.entries.some(e=>e.type===3&&Buffer.from(e.bin).equals(fs.readFileSync(path.join(scratch,`logo-${size}.png`)))));
fs.copyFileSync(path.join(root,'member-client/installer.nsi'),path.join(output,'installer.nsi'));
const cache=path.join(os.homedir(),'Library/Caches/electron-builder');
const nsisParent=fs.readdirSync(cache).find(n=>n.startsWith('nsis-3.'));
if(!nsisParent)throw Error('缺少已安装的NSIS编译器');
const bundle=fs.readdirSync(path.join(cache,nsisParent)).find(n=>fs.existsSync(path.join(cache,nsisParent,n,'mac/makensis')));
const makensis=process.env.ZHOUZHI_MAKENSIS||path.join(cache,nsisParent,bundle,'mac/makensis');
if(process.argv.includes('--prepare-only')){console.log(JSON.stringify({output,clientIconVerified:true,asarFiles:packed,preparedOnly:true}));process.exit(0);}
execFileSync(makensis,['installer.nsi'],{cwd:output,stdio:'inherit',env:{...process.env,NSISDIR:process.env.NSISDIR||path.join(cache,nsisParent,bundle)}});
const setup=path.join(output,'Zhouzhi-V1.0-Windows-x64-Setup.exe');
const installerRes=ResEdit.NtExecutableResource.from(ResEdit.NtExecutable.from(fs.readFileSync(setup)));
assert.ok(installerRes.entries.some(e=>e.type===3&&Buffer.from(e.bin).equals(fs.readFileSync(path.join(scratch,'logo-128.png')))),'安装程序必须包含同舟图标');
console.log(JSON.stringify({setup,clientIconVerified:true,installerIconVerified:true,asarFiles:packed,windowsNativeTest:false}));
