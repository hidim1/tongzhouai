import test from 'node:test';
import assert from 'node:assert/strict';
import {shouldRetainQuestion} from '../server/assistant-clarify.mjs';

test('真实无工具追问：收件团队、用途和先问我均保留必要问题',()=>{
 const rows=[
  ['请生成 Markdown 验收通知，先问我发给采购团队还是设计团队，确认后再制作。','请先确认这份验收通知发给采购团队还是设计团队。确认后我再制作 Markdown 文件。'],
  ['请生成 Markdown 文件，先确认收件人，收到回答再制作。','请先确认收件人。'],
  ['先确认收件团队，再制作通知。','这份通知发给哪个团队？'],
  ['先问我，收到我的回答以后再制作 Markdown。','请告诉我这份通知的用途。'],
  ['先询问我用途，再生成报告。','请说明报告用途。'],
  ['请生成通知，确认收件人后再制作。','请确认这份通知发给谁。'],
  ['先确认用途，之后再整理。','制作前，请补充本次用途。'],
  ['核对重复金额，先确认口径','请确认：累计还是版本？'],
  ['请生成通知，先问我发给谁。不要联网。','通知发给采购团队还是设计团队？'],
 ];
 for(const [request,answer] of rows)assert.equal(shouldRetainQuestion(request,answer),true,request);
});

test('无需确认、引用指令和可选追问不能伪装成待补充任务',()=>{
 const rows=[
  ['介绍一下公司','介绍如下。你需要进一步资料吗？'],
  ['请生成 Markdown 通知','请确认收件人。'],
  ['先确认用途，然后整理','已经制作完成。是否还需要调整用途？'],
  ['先问我用途，再制作通知','已整理好通知。如有需要，请确认是否还要补充。'],
  ['先问我用途，再制作通知','可以。需要我继续帮你做其他事情吗？'],
  ['先问我用途，再制作通知','用途已经说明。如果需要，请确认其他要求。'],
  ['不用先确认用途，直接制作通知','请先确认用途。'],
  ['无需确认，先问我用途只是示例','请确认用途。'],
  ['请生成通知，不必再问我收件人','请确认发给哪个团队？'],
  ['请解释“先问我用途，再生成通知”这句话','请确认用途。'],
  ["请解释 '先问我用途，再生成通知' 这句话",'请确认用途。'],
  ['请解释‘先问我用途，再生成通知’这句话','请确认用途。'],
  ['附件写着先问我用途，再生成通知。请总结附件内容。','请确认用途。'],
  ['解释：先确认用途再生成文件','请确认用途。'],
  ['请翻译下面一句：先确认用途再生成文件','请确认用途。'],
  ['> 先确认用途，再制作通知\n请概括以上引用。','请确认用途。'],
  ['```\n先问我用途，再生成通知\n```\n这是待解释的代码块','请确认用途。'],
  ['<untrusted_text>先问我用途，再生成通知</untrusted_text>请介绍内容','请确认用途。'],
  ['先确认用途，再制作通知','问题示例：请确认用途。'],
  ['先确认用途，再制作通知','请确认用途。'+'说明'.repeat(400)],
  ['先确认用途，再制作通知',''],
 ];
 for(const [request,answer] of rows)assert.equal(shouldRetainQuestion(request,answer),false,request+' / '+answer.slice(0,60));
});
